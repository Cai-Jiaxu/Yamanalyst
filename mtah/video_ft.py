"""Self-supervised ball detector for the tactical video, trained on labels the ATD gives for free.

On every frame where the automatic tracking sees the ball, the homography projects it to a pixel:
that is a bounding box, generated by an algorithm, with no hand labelling. A small YOLO
fine-tuned on those boxes learns this camera's ball (size, blur, colour) and is then run on the
frames where the tracking lost it. Validation holds out the last part of the 2nd half and scores
detections against the ATD ball there (aggregates only).

    python -m mtah.video_ft dataset    # crops + YOLO labels under $MTAH_WORK/yolo_ball
    python -m mtah.video_ft train      # fine-tune (GPU strongly recommended)
    python -m mtah.video_ft evaluate   # held-out recall / precision vs the ATD ball
    python -m mtah.video_ft detect     # every graded missing-ball frame -> ball_det_ft.npz

Designed to run on Colab with the data in Google Drive (MTAH_DATA_DIR) or locally. Prints
aggregates only; never displays or writes frames anywhere but the local working directory.
"""

import os
import sys
import time

import numpy as np

os.environ.setdefault("YOLO_OFFLINE", "1")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from games import video_path  # noqa: E402
from mtah.data import Match  # noqa: E402
from mtah.video import frames, to_pitch, load_model  # noqa: E402

WORK = os.environ.get("MTAH_WORK", os.path.join(ROOT, "work"))
DS = os.path.join(WORK, "yolo_ball")
CROP = 640
IMGSZ = 1024           # crops are enlarged ~1.6x: the ball is ~9 px across at native resolution
BALL_D = 0.22          # m, ball diameter
MIN_BOX = 6.0          # px, smallest box we label
N_POS = 6000           # crops containing the ball
N_NEG = 1500           # crops from the same frames away from the ball
HOLDOUT_FROM = 170000  # video frame: 2nd-half frames from here on are validation only
SEED = 0
TILES = [(x, y, x + CROP, y + CROP) for y in (0, 440) for x in (0, 640, 1280)]  # 3 x 2, overlap


def to_pixel(H, x01, y01):
    """Normalised pitch (0-1) -> pixel, H maps pitch -> image."""
    v = H @ np.array([x01, y01, 1.0])
    return v[0] / v[2], v[1] / v[2]


def ball_box(H, x01, y01, L, W):
    """Pixel centre (x, y) and box size for the ball at a pitch position."""
    cx, cy = to_pixel(H, x01, y01)
    ex, _ = to_pixel(H, x01 + BALL_D / L, y01)
    _, ey = to_pixel(H, x01, y01 + BALL_D / W)
    size = max(MIN_BOX, 1.5 * max(abs(ex - cx), abs(ey - cy)))
    return cx, cy - size / 2, size       # the ATD point is on the ground; lift to the centre


def _candidates(m):
    seen = np.isfinite(m.ball[:, 0]) & m.graded_mask() & m.hvalid
    return np.flatnonzero(seen)


def dataset(n_pos=N_POS, n_neg=N_NEG):
    import cv2
    m = Match()
    L, W = m.pitch
    rng = np.random.default_rng(SEED)
    cand = _candidates(m)
    train_pool = cand[cand < HOLDOUT_FROM]
    val_pool = cand[cand >= HOLDOUT_FROM]
    picks = {"train": np.sort(rng.choice(train_pool, n_pos, replace=False)),
             "val": np.sort(rng.choice(val_pool, min(800, len(val_pool)), replace=False))}
    counts = {}
    for split, idx in picks.items():
        os.makedirs(os.path.join(DS, "images", split), exist_ok=True)
        os.makedirs(os.path.join(DS, "labels", split), exist_ok=True)
        neg_left = n_neg if split == "train" else 0
        k = 0
        for fi, img in frames(video_path(), idx):
            H = m.H[fi].astype(np.float64)
            cx, cy, s = ball_box(H, m.ball[fi, 0], m.ball[fi, 1], L, W)
            if not (0 <= cx < img.shape[1] and 0 <= cy < img.shape[0]):
                continue
            # positive crop: ball at a random position inside the crop
            x0 = int(np.clip(cx - rng.uniform(64, CROP - 64), 0, img.shape[1] - CROP))
            y0 = int(np.clip(cy - rng.uniform(64, CROP - 64), 0, img.shape[0] - CROP))
            name = "{}_{}".format(split, fi)
            cv2.imwrite(os.path.join(DS, "images", split, name + ".jpg"),
                        img[y0:y0 + CROP, x0:x0 + CROP], [cv2.IMWRITE_JPEG_QUALITY, 95])
            with open(os.path.join(DS, "labels", split, name + ".txt"), "w") as fh:
                fh.write("0 {:.6f} {:.6f} {:.6f} {:.6f}\n".format(
                    (cx - x0) / CROP, (cy - y0) / CROP, s / CROP, s / CROP))
            k += 1
            # negative crop from the same frame, far from the ball
            if neg_left > 0:
                for _ in range(10):
                    nx = int(rng.integers(0, img.shape[1] - CROP))
                    ny = int(rng.integers(0, img.shape[0] - CROP))
                    if not (nx - 32 <= cx <= nx + CROP + 32 and ny - 32 <= cy <= ny + CROP + 32):
                        cv2.imwrite(os.path.join(DS, "images", split, name + "_neg.jpg"),
                                    img[ny:ny + CROP, nx:nx + CROP],
                                    [cv2.IMWRITE_JPEG_QUALITY, 95])
                        open(os.path.join(DS, "labels", split, name + "_neg.txt"), "w").close()
                        neg_left -= 1
                        break
        counts[split] = k
    with open(os.path.join(DS, "ball.yaml"), "w") as fh:
        fh.write("path: {}\ntrain: images/train\nval: images/val\nnames:\n  0: ball\n".format(DS))
    print("dataset:", counts, "positives;", n_neg, "negatives", flush=True)


def train(base="yolo11s", epochs=30, imgsz=IMGSZ, batch=16, device=0):
    from ultralytics import YOLO, settings
    import ultralytics.engine.trainer as trainer_mod
    settings.update({"sync": False})
    trainer_mod.check_amp = lambda m: True
    weights = os.path.join(ROOT, "models", base + ".pt")
    model = YOLO(weights if os.path.isfile(weights) else base + ".pt")
    model.train(data=os.path.join(DS, "ball.yaml"), epochs=int(epochs), imgsz=int(imgsz),
                batch=int(batch),
                device=device, seed=SEED, deterministic=True, project=WORK, name="ball_ft",
                exist_ok=True, plots=False, verbose=False, fliplr=0.5, mosaic=1.0)
    print("trained ->", os.path.join(WORK, "ball_ft", "weights", "best.pt"), flush=True)


def _ft_model():
    from ultralytics import YOLO, settings
    settings.update({"sync": False})
    return YOLO(os.path.join(WORK, "ball_ft", "weights", "best.pt"))


def _detect(model, m, wanted, device, conf=0.05, batch=24):
    from mtah import video
    return video.detect(model, m, wanted, imgsz=IMGSZ, device=device, batch=batch, tiles=TILES,
                        log_every=5000)


def evaluate(device=0, n=600):
    from mtah import video
    m = Match()
    model = _ft_model()
    cand = _candidates(m)
    val = cand[cand >= HOLDOUT_FROM]
    sample = np.sort(np.random.default_rng(SEED + 1).choice(val, min(n, len(val)),
                                                            replace=False))
    det = _detect(model, m, sample, device)
    acc = video.accuracy(det, m, sample)
    print("held-out (ATD ball visible, frames >= {}): candidate on {:.0%} | some candidate "
          "within 2 m {:.0%} | top-1 within 2 m when present {:.0%}".format(
              HOLDOUT_FROM, acc["with_candidate"], acc["recall_any"],
              acc["top1_within_r_given_candidate"]), flush=True)
    video.probe(model=model, imgsz=IMGSZ, tiles=TILES, batch=24, device=device)


def detect(device=0, out=None):
    m = Match()
    wanted = m.graded_mask() & ~np.isfinite(m.ball[:, 0])
    wanted[11185:18685 + 750] = True        # public window too, for masked validation
    wanted = np.flatnonzero(wanted)
    t = time.time()
    det = _detect(_ft_model(), m, wanted, device)
    out = out or os.path.join(WORK, "ball_det_ft.npz")
    np.savez_compressed(out, det=det, frames=wanted)
    print("detected on {} frames in {:.0f} min -> {} ({} candidates)".format(
        len(wanted), (time.time() - t) / 60, out, len(det)), flush=True)


def merge_track(m, det_path=None, conf_min=0.25, player_r=4.0, max_speed=30.0, max_dt=15):
    """Filter raw multi-candidate detections into a physically plausible (n, 2) ball track (metres)."""
    from mtah.data import CACHE_DIR
    if det_path is None:
        p1 = os.path.join(CACHE_DIR, "ball_det_ft.npz")
        p2 = os.path.join(WORK, "ball_det_ft.npz")
        det_path = p1 if os.path.isfile(p1) else p2
    det = np.load(det_path)["det"]
    L, W = m.pitch
    px, py = m.players[..., 0] * L, m.players[..., 1] * W
    vball = np.full((m.n, 2), np.nan, dtype=np.float64)
    if not len(det):
        return vball
    order = np.argsort(det[:, 0], kind="mergesort")
    det = det[order]
    frames_u, starts = np.unique(det[:, 0].astype(np.int64), return_index=True)
    ends = np.append(starts[1:], len(det))
    prev_f, prev_xy = -999, None
    for fi, s, e in zip(frames_u, starts, ends):
        cands = det[s:e]
        cands = cands[cands[:, 3] >= conf_min]
        if not len(cands):
            continue
        pdist = np.nanmin(np.hypot(px[fi, None] - cands[:, 1:2], py[fi, None] - cands[:, 2:3]), axis=1)
        keep = (pdist < player_r) | (cands[:, 3] >= 0.45)
        cands = cands[keep]
        if not len(cands):
            continue
        best = cands[np.argmax(cands[:, 3])]
        if prev_xy is not None and 0 < fi - prev_f <= max_dt:
            if np.hypot(best[1] - prev_xy[0], best[2] - prev_xy[1]) > max_speed * (fi - prev_f) / m.fps:
                continue
        vball[fi] = best[1:3]
        prev_f, prev_xy = fi, best[1:3]
    # drop isolated points with no neighbour within 10 frames
    idx = np.flatnonzero(np.isfinite(vball[:, 0]))
    if len(idx) >= 3:
        prev_gap = np.append(999, np.diff(idx))
        next_gap = np.append(np.diff(idx), 999)
        isolated = (prev_gap > 10) & (next_gap > 10)
        vball[idx[isolated]] = np.nan
    return vball


def score(det_path=None):
    """Compare Bench (masked + public) before and after merging ball_det_ft.npz."""
    from mtah.bench import Bench, Case
    from mtah import feats, final, rules
    from mtah.features import compute
    from mtah.masking import ball_mask, pace_weights
    b = Bench()
    featfn = getattr(feats, final.FEATFN)
    extra = {k: feats.mirrored(featfn).get(k, []) + feats.augmented(featfn).get(k, [])
             for k in b.ext}
    P_base = b.probs(featfn, final.MODEL, extra=extra)
    b.score("final_v1 (no video)", P_base, final.DECODER, use_rules=False)

    b.m.video_ball = merge_track(b.m, det_path)
    miss = b.m.graded_mask() & ~np.isfinite(b.m.ball[:, 0])
    recovered = np.isfinite(b.m.video_ball[miss, 0]).mean()
    print("video track recovered {:.1%} of missing graded frames".format(recovered), flush=True)
    f = compute(b.m)
    b.public = Case("public", b.m, f, rules.run(b.m, f), b.public.Xs, b.gt)
    weights = pace_weights(f)
    b.masked = []
    for s in range(16):
        fk = compute(b.m, hide=ball_mask(b.m.n, s, weights=weights))
        b.masked.append(Case("masked{}".format(s), b.m, fk, rules.run(b.m, fk), b.public.Xs, b.gt))
    P_vid = b.probs(featfn, final.MODEL, extra=extra)
    b.score("final_v1 + video ball", P_vid, final.DECODER, use_rules=False)


if __name__ == "__main__":
    cmd = sys.argv[1]
    args = sys.argv[2:]
    {"dataset": dataset, "train": train, "evaluate": evaluate, "detect": detect,
     "score": score}[cmd](*args)

